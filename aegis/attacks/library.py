def get_all_attacks() -> List[Dict]:
    return [
        {
            "id": atk.id,
            "name": atk.name,
            "category": atk.category,
            "severity_level": atk.severity_level,
            "description": atk.description,
            "prompt": atk.prompt,
            "target_tool_command": atk.target_tool_command,
            "mitre_atlas_tag": atk.mitre_atlas_tag,
            "is_adversarial": atk.is_adversarial,
        }
        for atk in WORKBENCH_TEMPLATES.values()
    ]


def get_attack_by_id(attack_id: str) -> Optional[AttackPayload]:
    return WORKBENCH_TEMPLATES.get(attack_id) or ATTACK_LIBRARY.get(attack_id)


